#!/usr/bin/env python3
"""Generate src/Bretaheim/Data/Dg.cs (DGROUP offset constants) from the decompilation's
globals_seed.jsonl. Names: g_brit_chunk_map -> Dg.BritChunkMap.

Usage: python3 tools/gen_dgroup.py [path/to/globals_seed.jsonl]
"""
import json, re, sys
from pathlib import Path

src = Path(sys.argv[1] if len(sys.argv) > 1 else
           Path.home() / "Projects/Ultima5Revolutions/analysis/globals_seed.jsonl")
dst = Path(__file__).resolve().parent.parent / "src/Bretaheim/Data/Dg.cs"

out = ["// <auto-generated> by tools/gen_dgroup.py from ~/Projects/Ultima5Revolutions/analysis/globals_seed.jsonl.",
       "// DGROUP offsets (DATA.OVL file offset - 0x10). Do not edit by hand; re-run the generator.", "",
       "namespace Bretaheim.Data", "{", "    public static class Dg", "    {"]
seen = set()
for line in src.read_text().splitlines():
    e = json.loads(line)
    n = e["name"]
    if not n.startswith("g_"):
        continue
    cs = re.sub(r"[^A-Za-z0-9]", "", "".join(p.capitalize() for p in n[2:].split("_")))
    if not cs or cs[0].isdigit():
        cs = "X" + cs
    if cs in seen:
        continue
    seen.add(cs)
    m = e["meaning"].replace("\n", " ")[:150].replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    out.append(f"        /// <summary>{e['type']}, {e['size']} B. {m}</summary>")
    out.append(f"        public const int {cs} = {e['off']};")
out += ["    }", "}", ""]
dst.write_text("\n".join(out))
print(f"{len(seen)} constants -> {dst}")
